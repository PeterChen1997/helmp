//! 剪贴板采集：轮询 changeCount，变化时读取内容并决定是否入库。
//!
//! NSPasteboard 没有变更通知，只能轮询（Maccy 0.5 s，这里 300 ms）。
//! 读取逻辑写在 `Pasteboard` trait 之上，测试用假实现驱动。

use std::path::PathBuf;

use super::store::{ImageFormat, NewClip, Source};
use crate::config::ClipboardConfig;

/// 轮询间隔。
pub const POLL_INTERVAL: std::time::Duration = std::time::Duration::from_millis(300);

/// 「隐藏」内容（nspasteboard.org 约定）：密码管理器（1Password、Bitwarden、钥匙串）写密码时会带上。
/// 若入库，明文密码就会落在磁盘上并出现在搜索结果里。受 `clipboard.skip_concealed` 控制。
pub const CONCEALED_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "com.agilebits.onepassword",
];

/// 「临时 / 自动生成」内容：写入方明确声明不该进历史（包括我们自己写回的条目），始终跳过。
pub const TRANSIENT_TYPES: &[&str] = &[
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    // 旧约定，仍有工具在用（Maccy 同样忽略）。
    "de.petermaurer.TransientPasteboardType",
];

/// 写回历史条目时打的标记：别的剪贴板工具（和我们自己的轮询）看到它就不会再记录一次。
pub const TRANSIENT_TYPE: &str = "org.nspasteboard.TransientType";

/// 剪贴板的只读视图。真实实现是 `macos::SystemPasteboard`。
pub trait Pasteboard {
    fn change_count(&self) -> isize;
    /// 当前内容带的全部 type（UTI）。
    fn types(&self) -> Vec<String>;
    /// 文件 URL 对应的本地路径（Finder 复制文件）。
    fn file_paths(&self) -> Vec<PathBuf>;
    fn text(&self) -> Option<String>;
    /// PNG 优先，其次 TIFF。
    fn image(&self) -> Option<Image>;
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Image {
    pub bytes: Vec<u8>,
    pub format: ImageFormat,
    pub width: u32,
    pub height: u32,
}

#[derive(Debug, PartialEq, Eq)]
pub enum Read {
    /// changeCount 没变，或读取过程中又变了（下个周期重读）。
    Unchanged,
    /// 带隐私标记，跳过。附带命中的 type。
    Private(String),
    /// 没有我们支持的内容（例如只有 RTF / 自定义 type）。
    Empty,
    /// 按配置不记录（关闭、忽略的 App、不记录图片），附原因。
    Ignored(&'static str),
    Clip(NewClip),
}

/// 按优先级读取当前内容：隐私标记 → 文件 → 文本 → 图片。
///
/// 文件优先于文本：Finder 复制文件时还会附带文件名文本和图标 TIFF，那些不是用户想要的。
/// 文本优先于图片：Excel / Keynote 复制时会附带一张渲染图，用户要的是文字。
pub fn read(pasteboard: &dyn Pasteboard, skip_concealed: bool) -> Read {
    let types = pasteboard.types();
    let private = |ty: &&String| {
        TRANSIENT_TYPES.contains(&ty.as_str())
            || (skip_concealed && CONCEALED_TYPES.contains(&ty.as_str()))
    };
    if let Some(private) = types.iter().find(private) {
        // 注意：命中后不再读任何内容，敏感数据连内存都不进。
        return Read::Private(private.clone());
    }
    let files = pasteboard.file_paths();
    if !files.is_empty() {
        return Read::Clip(NewClip::Files(files));
    }
    if let Some(text) = pasteboard.text().filter(|text| !text.is_empty()) {
        return Read::Clip(NewClip::Text(text));
    }
    if let Some(image) = pasteboard.image() {
        return Read::Clip(NewClip::Image {
            bytes: image.bytes,
            format: image.format,
            width: image.width,
            height: image.height,
        });
    }
    Read::Empty
}

/// 一个轮询周期。`last` 为 `None` 时（启动）无条件读一次，即「启动时采集当前剪贴板」。
///
/// 先按配置和前台 App 判断要不要记录（`gate`），不记录时连内容都不读：
/// 关掉记录、或者正在用密码 App 时，内容不进本进程内存。
pub fn poll(
    pasteboard: &dyn Pasteboard,
    last: &mut Option<isize>,
    config: &ClipboardConfig,
    source: Option<&Source>,
) -> Read {
    let before = pasteboard.change_count();
    if *last == Some(before) {
        return Read::Unchanged;
    }
    if let Some(reason) = gate(config, source) {
        *last = Some(before);
        return Read::Ignored(reason);
    }
    let read = match read(pasteboard, config.skip_concealed) {
        Read::Clip(clip) if !admits(config, &clip) => Read::Ignored("不记录图片和文件"),
        other => other,
    };
    if pasteboard.change_count() != before {
        // 读的过程中剪贴板又被改了，读到的可能是新旧混合，丢掉等下个周期。
        return Read::Unchanged;
    }
    *last = Some(before);
    read
}

/// 读内容之前的判断：关闭记录、或复制来自被忽略的 App，返回原因。
pub fn gate(config: &ClipboardConfig, source: Option<&Source>) -> Option<&'static str> {
    if !config.enabled {
        return Some("剪贴板历史已关闭");
    }
    let bundle = source.and_then(|source| source.bundle_id.as_deref())?;
    config
        .ignore_apps
        .iter()
        .any(|ignored| ignored.eq_ignore_ascii_case(bundle))
        .then_some("来源 App 在忽略列表里")
}

/// 读到内容之后的判断：`record_images` 关闭时图片和文件都不记录（设置里写的是「记录图片和文件」）。
fn admits(config: &ClipboardConfig, clip: &NewClip) -> bool {
    config.record_images || matches!(clip, NewClip::Text(_))
}

#[cfg(test)]
pub(crate) mod tests {
    use std::cell::{Cell, RefCell};

    use super::*;

    /// 假剪贴板：记录内容被读过几次，用来证明隐私内容根本没被读取。
    #[derive(Default)]
    pub(crate) struct FakePasteboard {
        pub change: Cell<isize>,
        pub types: RefCell<Vec<String>>,
        pub files: RefCell<Vec<PathBuf>>,
        pub text: RefCell<Option<String>>,
        pub image: RefCell<Option<Image>>,
        pub content_reads: Cell<usize>,
        /// 读取内容时把 changeCount 加一，模拟读取期间被别的 App 改写。
        pub bump_on_read: Cell<bool>,
    }

    impl FakePasteboard {
        pub(crate) fn set_text(&self, text: &str, extra_types: &[&str]) {
            self.change.set(self.change.get() + 1);
            let mut types = vec!["public.utf8-plain-text".to_string()];
            types.extend(extra_types.iter().map(|ty| ty.to_string()));
            *self.types.borrow_mut() = types;
            *self.files.borrow_mut() = Vec::new();
            *self.text.borrow_mut() = Some(text.to_string());
            *self.image.borrow_mut() = None;
        }

        fn content_read(&self) {
            self.content_reads.set(self.content_reads.get() + 1);
            if self.bump_on_read.get() {
                self.change.set(self.change.get() + 1);
            }
        }
    }

    impl Pasteboard for FakePasteboard {
        fn change_count(&self) -> isize {
            self.change.get()
        }
        fn types(&self) -> Vec<String> {
            self.types.borrow().clone()
        }
        fn file_paths(&self) -> Vec<PathBuf> {
            self.content_read();
            self.files.borrow().clone()
        }
        fn text(&self) -> Option<String> {
            self.content_read();
            self.text.borrow().clone()
        }
        fn image(&self) -> Option<Image> {
            self.content_read();
            self.image.borrow().clone()
        }
    }

    #[test]
    fn skips_concealed_transient_and_autogenerated_without_reading_content() {
        // 跳过 Concealed 是为了不把密码管理器复制的明文密码写进磁盘；
        // 连读都不读，避免密码进入本进程内存后被日志等意外带出。
        for marker in [
            "org.nspasteboard.ConcealedType",
            "org.nspasteboard.TransientType",
            "org.nspasteboard.AutoGeneratedType",
        ] {
            let pb = FakePasteboard::default();
            pb.set_text("hunter2", &[marker]);
            assert_eq!(read(&pb, true), Read::Private(marker.to_string()));
            assert_eq!(pb.content_reads.get(), 0, "{marker} 命中后不应读取内容");
        }
    }

    #[test]
    fn skip_concealed_off_records_passwords_but_never_transient() {
        // 用户在设置里关掉「跳过隐藏内容」就是要记录密码类内容；
        // 但 Transient 是写入方声明「别记」（含我们自己写回的条目），关了也照样跳过，否则选中一条就会重复记录。
        let pb = FakePasteboard::default();
        pb.set_text("hunter2", &["org.nspasteboard.ConcealedType"]);
        assert_eq!(
            read(&pb, false),
            Read::Clip(NewClip::Text("hunter2".into()))
        );
        pb.set_text("x", &[TRANSIENT_TYPE]);
        assert_eq!(read(&pb, false), Read::Private(TRANSIENT_TYPE.into()));
    }

    fn source(bundle: &str) -> Source {
        Source {
            name: "App".into(),
            bundle_id: Some(bundle.into()),
        }
    }

    #[test]
    fn ignored_apps_and_disabled_history_are_not_even_read() {
        // 「不记录以下应用」主要用来挡密码 App：连读都不读，内容不进本进程内存。
        let config = ClipboardConfig::default();
        let pb = FakePasteboard::default();
        pb.set_text("secret", &[]);
        let mut last = None;
        let passwords = source("com.apple.Passwords");
        assert!(matches!(
            poll(&pb, &mut last, &config, Some(&passwords)),
            Read::Ignored(_)
        ));
        assert_eq!(pb.content_reads.get(), 0);
        // 跳过之后同一份内容不会在下个周期又被读进来。
        assert_eq!(
            poll(&pb, &mut last, &config, Some(&source("com.apple.Safari"))),
            Read::Unchanged
        );

        let disabled = ClipboardConfig {
            enabled: false,
            ..ClipboardConfig::default()
        };
        pb.set_text("anything", &[]);
        assert!(matches!(
            poll(&pb, &mut last, &disabled, None),
            Read::Ignored(_)
        ));
        assert_eq!(pb.content_reads.get(), 0);
        // 未知来源（启动时补采集）不受忽略列表影响。
        assert_eq!(gate(&config, None), None);
        assert!(gate(&config, Some(&source("COM.APPLE.PASSWORDS"))).is_some());
    }

    #[test]
    fn record_images_off_skips_images_and_files_but_keeps_text() {
        // 设置项文案是「记录图片和文件」：关掉后两者都不入库，文字照常记录。
        let config = ClipboardConfig {
            record_images: false,
            ..ClipboardConfig::default()
        };
        let pb = FakePasteboard::default();
        pb.set_text("report.pdf", &["public.file-url"]);
        *pb.files.borrow_mut() = vec![PathBuf::from("/tmp/report.pdf")];
        let mut last = None;
        assert!(matches!(
            poll(&pb, &mut last, &config, None),
            Read::Ignored(_)
        ));
        pb.set_text("plain", &[]);
        assert_eq!(
            poll(&pb, &mut last, &config, None),
            Read::Clip(NewClip::Text("plain".into()))
        );
    }

    #[test]
    fn files_win_over_filename_text_and_icon() {
        // Finder 复制文件会附带文件名文本；若按文本记录，写回后就粘贴不出文件了。
        let pb = FakePasteboard::default();
        pb.set_text("report.pdf", &["public.file-url"]);
        *pb.files.borrow_mut() = vec![PathBuf::from("/tmp/report.pdf")];
        assert_eq!(
            read(&pb, true),
            Read::Clip(NewClip::Files(vec![PathBuf::from("/tmp/report.pdf")]))
        );
    }

    #[test]
    fn image_only_when_no_text() {
        let pb = FakePasteboard::default();
        pb.change.set(1);
        *pb.types.borrow_mut() = vec!["public.png".into()];
        *pb.image.borrow_mut() = Some(Image {
            bytes: vec![1, 2, 3],
            format: ImageFormat::Png,
            width: 4,
            height: 5,
        });
        assert!(matches!(
            read(&pb, true),
            Read::Clip(NewClip::Image { width: 4, .. })
        ));
    }

    #[test]
    fn poll_reads_on_startup_then_only_on_change() {
        // 启动时必须采集一次（否则启动前最后复制的内容永远进不了历史），
        // 之后 changeCount 不变就不读，轮询才足够便宜。
        let pb = FakePasteboard::default();
        pb.set_text("first", &[]);
        let mut last = None;
        assert_eq!(
            poll(&pb, &mut last, &ClipboardConfig::default(), None),
            Read::Clip(NewClip::Text("first".into()))
        );
        assert_eq!(
            poll(&pb, &mut last, &ClipboardConfig::default(), None),
            Read::Unchanged
        );
        pb.set_text("second", &[]);
        assert_eq!(
            poll(&pb, &mut last, &ClipboardConfig::default(), None),
            Read::Clip(NewClip::Text("second".into()))
        );
    }

    #[test]
    fn poll_retries_when_changed_during_read() {
        // 读取期间剪贴板被改写时丢弃本次结果，下个周期重读，避免记下半新半旧的内容。
        let pb = FakePasteboard::default();
        pb.set_text("racy", &[]);
        pb.bump_on_read.set(true);
        let mut last = None;
        assert_eq!(
            poll(&pb, &mut last, &ClipboardConfig::default(), None),
            Read::Unchanged
        );
        assert_eq!(last, None);
        pb.bump_on_read.set(false);
        assert_eq!(
            poll(&pb, &mut last, &ClipboardConfig::default(), None),
            Read::Clip(NewClip::Text("racy".into()))
        );
    }
}
