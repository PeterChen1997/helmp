#!/usr/bin/env python3
"""生成 Emoji 与符号表：src/providers/emoji/data.tsv（编译期 include_str! 嵌入）。

数据来源（Unicode License v3，署名见 docs/THIRD_PARTY.md）：
- CLDR 注释（英文、简体中文）：npm 包 cldr-annotations-full，名称（tts）与关键词（default）。
- Unicode emoji-test.txt：emoji 的排列顺序、完全限定写法（带 FE0F），以及哪些 emoji 支持肤色。
另外手写补充一小批 Mac 按键符号（⌘ ⌥ ⌃ …），CLDR 里没有它们。

用法：python3 script/gen-emoji.py            # 下载固定版本并重写 data.tsv
     python3 script/gen-emoji.py <dir>      # 用 <dir> 里已下载的 en.json / zh.json / emoji-test.txt

输出每行一项，制表符分隔：字符、标记（e = emoji，s = 符号，t = 支持肤色）、英文名、英文关键词（| 分隔）、
中文名、中文关键词。第一行是 `#` 开头的版本说明。
"""

import json
import sys
import urllib.request
from pathlib import Path

CLDR_VERSION = "49.0.0"
EMOJI_VERSION = "18.0"
CLDR_URL = "https://cdn.jsdelivr.net/npm/cldr-annotations-full@{v}/annotations/{lang}/annotations.json"
EMOJI_TEST_URL = "https://www.unicode.org/Public/{v}.0/emoji/emoji-test.txt"

OUT = Path(__file__).resolve().parent.parent / "src/providers/emoji/data.tsv"

# CLDR 没有的 Mac 按键符号：(字符, 英文名, 英文关键词, 中文名, 中文关键词)
EXTRA = [
    ("⌘", "command key", ["cmd", "command", "mac", "key"], "Command 键", ["命令键", "苹果键", "按键"]),
    ("⌥", "option key", ["opt", "option", "alt", "mac", "key"], "Option 键", ["选项键", "按键"]),
    ("⌃", "control key", ["ctrl", "control", "mac", "key"], "Control 键", ["控制键", "按键"]),
    ("⇪", "caps lock key", ["caps", "lock", "key"], "大写锁定键", ["大写", "按键"]),
    ("↩", "return key", ["return", "enter", "key"], "回车键", ["回车", "换行", "按键"]),
    ("⌫", "delete key", ["delete", "backspace", "key"], "删除键", ["退格", "删除", "按键"]),
    ("⌦", "forward delete key", ["delete", "forward", "key"], "向前删除键", ["删除", "按键"]),
    ("⎋", "escape key", ["esc", "escape", "key"], "Esc 键", ["退出键", "按键"]),
    ("⇥", "tab key", ["tab", "key"], "Tab 键", ["制表键", "按键"]),
    ("␣", "space key", ["space", "key"], "空格键", ["空格", "按键"]),
    ("", "apple logo", ["apple", "logo", "mac"], "苹果标志", ["苹果", "标志"]),
]


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def load(source: Path | None):
    if source:
        en = (source / "en.json").read_bytes()
        zh = (source / "zh.json").read_bytes()
        test = (source / "emoji-test.txt").read_bytes()
    else:
        en = fetch(CLDR_URL.format(v=CLDR_VERSION, lang="en"))
        zh = fetch(CLDR_URL.format(v=CLDR_VERSION, lang="zh"))
        test = fetch(EMOJI_TEST_URL.format(v=EMOJI_VERSION))
    table = lambda raw: json.loads(raw)["annotations"]["annotations"]
    return table(en), table(zh), test.decode("utf-8")


def emoji_order(test: str):
    """emoji-test.txt 里完全限定的 emoji，按文件顺序；另返回支持肤色的基础 emoji（去掉 FE0F）。"""
    order, skin = [], set()
    tones = {chr(c) for c in range(0x1F3FB, 0x1F400)}
    for line in test.splitlines():
        if not line or line.startswith("#") or "; fully-qualified" not in line:
            continue
        codes = line.split(";")[0].split()
        text = "".join(chr(int(code, 16)) for code in codes)
        if len(codes) == 2 and text[-1] in tones:
            skin.add(text[0])
            continue
        if any(ch in tones for ch in text):
            continue
        order.append(text)
    return order, skin


def clean(words):
    return "|".join(w.replace("\t", " ").replace("|", "/").strip() for w in words if w.strip())


def main():
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    en, zh, test = load(source)
    order, skin = emoji_order(test)
    rows, seen = [], set()

    def add(char, flags, en_entry, zh_entry):
        if char in seen or not en_entry or not zh_entry:
            return
        seen.add(char)
        bare = char.replace("️", "")
        en_name = (en_entry.get("tts") or [""])[0]
        zh_name = (zh_entry.get("tts") or [""])[0]
        if not en_name or not zh_name:
            return
        if bare in skin:
            flags += "t"
        rows.append("\t".join([char, flags, en_name, clean(en_entry.get("default", [])),
                               zh_name, clean(zh_entry.get("default", []))]))

    for char in order:
        bare = char.replace("️", "")
        key = char if char in en else bare
        add(char, "e", en.get(key), zh.get(key))
    emoji_keys = {c.replace("️", "") for c in order}
    for key in en:
        if key.replace("️", "") in emoji_keys:
            continue
        add(key, "s", en.get(key), zh.get(key))
    for char, en_name, en_kw, zh_name, zh_kw in EXTRA:
        add(char, "s", {"tts": [en_name], "default": en_kw}, {"tts": [zh_name], "default": zh_kw})

    header = f"# CLDR {CLDR_VERSION} annotations (en, zh) + Unicode emoji {EMOJI_VERSION}; Unicode License v3. Generated by script/gen-emoji.py"
    OUT.write_text(header + "\n" + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} rows to {OUT}")


if __name__ == "__main__":
    main()
